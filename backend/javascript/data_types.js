//                                               Types of Data

// String{All the characters between ""}

console.log("String Data Type");

const name = "Aman";

console.log(name);
console.log(typeof name); // typeof is used to find the type of data.

// Number{It includes all integers decimals and fractions}

console.log("\nNumber Data Type"); // ("\n") is used to move on next line

let age = 18;
let height = 5.9;

console.log("Age:", age, "height:", height);
console.log(typeof age, typeof height);

// Boolean{Either True or False}

console.log("\nBoolean Data Type");

const adult = 1 == "1"; // == is used to check the value
const minor = 2 === "2"; // === is used to check both value and data type

console.log("Adult: ", adult, "Minor: ", minor);
console.log(typeof adult, typeof minor);
