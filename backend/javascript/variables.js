// Types of variables

// let {reassignable}

console.log("let variable");

let x = 10;
console.log(x); // output: 10
x = 15;
console.log(x); // output: 15

// const variable {cannot be reassigned or redeclared}

console.log("\nconst variable");

const y = 3;
console.log(y); // output: 3
y = 5;
console.log(y); // output: error
